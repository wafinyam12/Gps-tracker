    <h1>Kebijakan Privasi</h1>
    <p class="updated">Sales Daily · Terakhir diperbarui: 5 Oktober 2026</p>

    <p>Kebijakan ini menjelaskan bagaimana aplikasi Sales Daily mengumpulkan, menggunakan, menyimpan, dan membagikan data saat Anda menggunakan aplikasi. Aplikasi disediakan untuk kebutuhan operasional organisasi dan hanya dapat digunakan dengan akun yang diberikan organisasi.</p>

    <h2>Data yang diproses</h2>
    <ul>
        <li><strong>Data akun:</strong> nama, username, email, nomor telepon, peran, dan informasi cabang yang terkait dengan akun Anda.</li>
        <li><strong>Data kunjungan dan pelanggan:</strong> informasi yang Anda masukkan saat mencatat kunjungan, termasuk foto yang dipilih atau diambil untuk kunjungan, serta data toko/pelanggan yang diperlukan oleh alur kerja.</li>
        <li><strong>Data lokasi:</strong> jika izin lokasi diberikan, koordinat, akurasi, kecepatan, arah, waktu pengambilan, dan indikator lokasi simulasi dapat dikirim saat aplikasi digunakan atau berjalan di latar belakang untuk pencatatan dan pemantauan kunjungan.</li>
        <li><strong>Data diagnostik:</strong> catatan teknis terbatas untuk membantu menemukan kegagalan aplikasi. Catatan dirancang untuk tidak menyimpan token, kata sandi, isi formulir, atau URL foto bertanda tangan; catatan lokal dibersihkan setelah tujuh hari dan Anda dapat memilih untuk membagikannya dari halaman Profil.</li>
        <li><strong>Data tersimpan sementara di perangkat:</strong> sebagian data yang diperlukan untuk antrean sinkronisasi offline dan draf fitur dapat disimpan di perangkat sampai tersinkron atau dihapus.</li>
    </ul>

    <h2>Tujuan penggunaan</h2>
    <p>Data digunakan untuk mengautentikasi pengguna, mengelola akun dan cabang, mencatat serta memverifikasi kunjungan, menampilkan peta dan ringkasan operasional, menyinkronkan pekerjaan saat koneksi tersedia, dan mendiagnosis masalah aplikasi. Organisasi yang memberikan akun Anda menentukan tujuan operasional dan hak akses atas data kerja tersebut.</p>

    <h2>Lokasi dan pilihan Anda</h2>
    <p>Pelacakan lokasi latar belakang memerlukan penjelasan dan persetujuan di aplikasi serta izin lokasi dari sistem Android. Jika Anda menolak, fitur lain yang tidak memerlukan lokasi tetap dapat digunakan. Anda dapat mengubah izin melalui Pengaturan Android atau menonaktifkan pelacakan yang tersedia di aplikasi. Penonaktifan izin menghentikan pengiriman lokasi berikutnya, tetapi tidak otomatis menghapus catatan kunjungan yang sudah tersimpan.</p>

    <h2>Penyimpanan dan pembagian data</h2>
    <p>Data akun, kunjungan, lokasi, dan foto dikirim ke backend organisasi melalui koneksi jaringan aplikasi dan hanya dapat diakses sesuai akun serta peran yang diberikan. Foto kunjungan baru disimpan pada penyimpanan privat backend. Administrator organisasi mengatur akses operasional dan masa retensi data server. Data offline tetap berada di perangkat sampai sinkronisasi berhasil atau Anda memilih menghapusnya.</p>
    <p>Peta menggunakan layanan ubin OpenStreetMap; saat peta dimuat, permintaan peta dapat mengungkap alamat IP dan area peta yang diminta kepada penyedia ubin. Jika Anda memilih membuka petunjuk arah, aplikasi dapat meneruskan koordinat tujuan ke aplikasi peta eksternal yang Anda pilih. Layanan eksternal tunduk pada kebijakan privasi masing-masing.</p>
    <p>Data juga dapat diproses oleh sistem bisnis yang dikonfigurasi organisasi untuk mendukung operasionalnya. Silakan hubungi administrator organisasi untuk mengetahui sistem dan aturan retensi yang berlaku pada akun Anda.</p>

    <h2>Keamanan</h2>
    <p>Aplikasi menerapkan pembatasan akses berbasis akun dan peran, menyimpan token sesi menggunakan penyimpanan aman perangkat, serta membatasi akses ke foto kunjungan baru. Tidak ada metode transmisi atau penyimpanan yang dapat dijamin sepenuhnya aman; jaga kerahasiaan perangkat dan kredensial Anda, dan laporkan dugaan akses tanpa izin kepada administrator organisasi.</p>

    <h2>Permintaan dan kontak</h2>
    <p>Untuk meminta akses, koreksi, atau penghapusan data, atau untuk mengajukan pertanyaan tentang kebijakan ini, hubungi administrator organisasi yang memberikan akun Sales Daily kepada Anda. Permintaan dapat tunduk pada kewajiban pencatatan dan retensi organisasi.</p>

